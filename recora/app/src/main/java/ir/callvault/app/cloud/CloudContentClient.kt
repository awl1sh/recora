package ir.callvault.app.cloud

import android.content.Context
import org.json.JSONArray
import org.json.JSONObject
import java.net.HttpURLConnection
import java.net.URL

/**
 * Read-only CallVault announcements/ads sync.
 * Set CLOUD_API_TOKEN in app/build.gradle.kts after installing the PHP panel.
 * The token is a public client credential (extractable from APK), never an admin password.
 */
object CloudContentClient {
    private const val PREFS = "callvault_cloud_content"
    private const val API_URL = "https://hajirobot.ir/foxvpn/api.php"
    // Replace this placeholder with the read-only API key generated by the PHP installer.
    private const val API_TOKEN = "REPLACE_WITH_PANEL_API_KEY"

    data class Snapshot(val notices: JSONArray, val ads: JSONArray, val fetchedAt: Long)

    fun sync(context: Context): Snapshot? {
        if (API_TOKEN.startsWith("REPLACE_")) return cached(context)
        var connection: HttpURLConnection? = null
        return try {
            connection = (URL(API_URL).openConnection() as HttpURLConnection).apply {
                requestMethod = "GET"
                connectTimeout = 8000
                readTimeout = 8000
                setRequestProperty("Authorization", "Bearer $API_TOKEN")
                setRequestProperty("Accept", "application/json")
            }
            if (connection.responseCode !in 200..299) return cached(context)
            val body = connection.inputStream.bufferedReader(Charsets.UTF_8).use { it.readText() }
            val json = JSONObject(body)
            if (!json.optBoolean("ok")) return cached(context)
            val notices = json.optJSONArray("notices") ?: JSONArray()
            val ads = json.optJSONArray("ads") ?: JSONArray()
            val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            prefs.edit()
                .putString("notices", notices.toString())
                .putString("ads", ads.toString())
                .putLong("fetched_at", System.currentTimeMillis())
                .apply()
            Snapshot(notices, ads, System.currentTimeMillis())
        } catch (_: Exception) {
            cached(context)
        } finally {
            connection?.disconnect()
        }
    }

    fun cached(context: Context): Snapshot {
        val p = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
        return Snapshot(
            runCatching { JSONArray(p.getString("notices", "[]")) }.getOrDefault(JSONArray()),
            runCatching { JSONArray(p.getString("ads", "[]")) }.getOrDefault(JSONArray()),
            p.getLong("fetched_at", 0L)
        )
    }
}
